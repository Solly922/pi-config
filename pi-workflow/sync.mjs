#!/usr/bin/env node
// Writes the Claude Code and Codex versions of the pi config in ~/.pi/agent.
// Usage: node sync.mjs [--dry-run] [--root <dir>]
// --root writes into <dir> instead of $HOME, for previews and tests.

import { spawnSync } from 'node:child_process';
import {
  existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync, realpathSync, renameSync, rmSync, statSync, symlinkSync,
  unlinkSync, writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PI_ROOT = join(homedir(), '.pi');
const PI_AGENT = join(PI_ROOT, 'agent');
const HERE = dirname(fileURLToPath(import.meta.url));
const RULES_DIR = join(HERE, 'rules');

const DRY_RUN = process.argv.includes('--dry-run');
const ROOT = rootArgument();
const DEST = ROOT ?? homedir();

// Sync writes where the CLIs read: both honor these variables. --root overrides them, so previews
// and tests never touch the real config.
const CLAUDE_HOME = ROOT ? join(ROOT, '.claude') : process.env.CLAUDE_CONFIG_DIR || join(homedir(), '.claude');
// Claude keeps its MCP servers in ~/.claude.json, or inside CLAUDE_CONFIG_DIR when that is set.
const CLAUDE_JSON = ROOT || process.env.CLAUDE_CONFIG_DIR ? join(CLAUDE_HOME, '.claude.json') : join(homedir(), '.claude.json');
const CLAUDE_ENV = { ...process.env, ...(ROOT ? { CLAUDE_CONFIG_DIR: CLAUDE_HOME } : {}) };
const CODEX_HOME = ROOT ? join(ROOT, '.codex') : process.env.CODEX_HOME || join(homedir(), '.codex');
const CODEX_ENV = { ...process.env, CODEX_HOME };
const CODEX_CONFIG = join(CODEX_HOME, 'config.toml');

const SKILL_SOURCES = [
  join(PI_AGENT, 'skills'),
  join(PI_AGENT, 'pi-hermes-memory', 'skills'),
  join(PI_AGENT, 'git', 'github.com', 'DietrichGebert', 'ponytail', 'skills'),
];
const SKILL_TARGETS = [join(CLAUDE_HOME, 'skills'), join(DEST, '.agents', 'skills')];
const CLAUDE_AGENTS = join(CLAUDE_HOME, 'agents');
const CODEX_AGENTS = join(CODEX_HOME, 'agents');
// pi MCP servers start a sync after skill_manage, so several can run at once.
const SYNC_LOCK = join(DEST, '.cache', 'pi-workflow-sync.lock');
const SYNC_LOCK_WAIT_MS = 30_000;
// A lock with no owner file yet belongs to a sync that crashed between mkdir and writing it.
const SYNC_LOCK_ORPHAN_MS = 10_000;
const CLI_TIMEOUT_MS = 20_000;

const GENERATED = 'generated by ~/.pi/pi-workflow/sync.mjs';
const MARKDOWN_MARKERS = { start: '<!-- pi-workflow:start -->', end: '<!-- pi-workflow:end -->' };
const TOML_MARKERS = { start: '# pi-workflow:start', end: '# pi-workflow:end' };
// Codex stops reading AGENTS.md at project_doc_max_bytes, 32 KiB by default.
const CODEX_DOC_LIMIT = 32 * 1024;

// Claude's stdio servers carry this variable so sync can tell its entries from the user's own.
const OWNER_ENV = { PI_WORKFLOW: '1' };
const MCP_SERVERS = {
  pi: {
    command: 'node',
    args: [join(HERE, 'mcp', 'pi-server.mjs')],
    // Codex passes MCP servers only a few variables. route needs TypeSafe's key, Hermes runs `pi`
    // from PATH, and the sync after skill_manage needs the profile folders.
    codex: { env_vars: ['TYPESAFE_API_KEY', 'PATH', 'CODEX_HOME', 'CLAUDE_CONFIG_DIR'], startup_timeout_sec: 30 },
  },
  'llm-wiki': {
    command: 'node',
    args: [join(PI_AGENT, 'npm', 'node_modules', '@zosmaai', 'pi-llm-wiki', 'dist', 'mcp', 'index.js')],
    // From the package's docs/harnesses.md.
    codex: { startup_timeout_sec: 20, tool_timeout_sec: 120 },
  },
  codegraph: { command: 'codegraph', args: ['serve', '--mcp'] },
  context7: { url: 'https://mcp.context7.com/mcp' },
  gh_grep: { url: 'https://mcp.grep.app' },
};

const PROVIDERS = { 'claude-bridge': 'claudeAgent', anthropic: 'claudeAgent', 'openai-codex': 'codex', 'openai-codex-fast': 'codex' };
// An agent whose preferred model is on the other provider runs on these when delegate_task is
// unavailable. Both come from the Model Routing table: Sonnet for bounded checks, Astra by default.
const FALLBACK_MODELS = { claudeAgent: 'claude-sonnet-5-5', codex: 'gpt-6-astra' };
const EFFORTS = ['low', 'medium', 'high', 'xhigh', 'max'];
const CLAUDE_TOOLS = { read: 'Read', grep: 'Grep', find: 'Glob', ls: 'Glob', bash: 'Bash', write: 'Write', edit: 'Edit' };

if (import.meta.main) main();

function main() {
  try {
    withSyncLock(() => {
      const rules = renderRules();
      writeBlock(join(CLAUDE_HOME, 'CLAUDE.md'), rules, MARKDOWN_MARKERS);
      writeBlock(join(CODEX_HOME, 'AGENTS.md'), rules, MARKDOWN_MARKERS, { byteLimit: CODEX_DOC_LIMIT });

      syncSkills();
      syncAgents();
      syncClaudeServers();
      syncCodexServers();
    });
  } catch (error) {
    console.error(`pi-workflow sync failed: ${error.message}`);
    process.exitCode = 1;
  }
}

function withSyncLock(work) {
  if (DRY_RUN) return work();

  mkdirSync(dirname(SYNC_LOCK), { recursive: true });
  const owner = join(SYNC_LOCK, 'pid');
  const deadline = Date.now() + SYNC_LOCK_WAIT_MS;

  // mkdir is atomic, so exactly one process creates the lock directory. A lock is taken over only
  // when its owner is gone; two waiters taking over the same dead lock at once is still possible.
  while (!tryMkdir(SYNC_LOCK)) {
    if (isStaleLock(owner)) {
      rmSync(SYNC_LOCK, { recursive: true, force: true });
    } else if (Date.now() > deadline) {
      throw new Error(`another sync still holds ${SYNC_LOCK}; remove it if no sync is running`);
    } else {
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
    }
  }

  writeFileSync(owner, String(process.pid));

  try {
    return work();
  } finally {
    // A sync whose lock was taken over must not delete the new owner's lock.
    if (lockOwner(owner) === process.pid) rmSync(SYNC_LOCK, { recursive: true, force: true });
  }
}

function lockOwner(owner) {
  try {
    return Number(readFileSync(owner, 'utf8'));
  } catch {
    return undefined;
  }
}

function isStaleLock(owner) {
  const pid = lockOwner(owner);

  // No owner file: either the lock just appeared or its creator died before writing it.
  if (pid === undefined) {
    const created = statSync(SYNC_LOCK, { throwIfNoEntry: false })?.mtimeMs;
    return created !== undefined && Date.now() - created > SYNC_LOCK_ORPHAN_MS;
  }

  try {
    process.kill(pid, 0);
    return false;
  } catch (error) {
    return error.code === 'ESRCH';
  }
}

function tryMkdir(path) {
  try {
    mkdirSync(path);
    return true;
  } catch (error) {
    if (error.code === 'EEXIST') return false;
    throw error;
  }
}

function rootArgument() {
  const index = process.argv.indexOf('--root');
  if (index === -1) return undefined;

  const root = process.argv[index + 1];
  if (root && !root.startsWith('--')) return root;

  console.error('pi-workflow sync failed: --root needs a directory');
  process.exit(2);
}

function renderRules() {
  const sections = splitSections(readFileSync(join(PI_AGENT, 'APPEND_SYSTEM.md'), 'utf8'));
  const overrides = loadRuleOverrides();

  for (const heading of overrides.keys()) {
    if (!sections.some((section) => section.heading === heading)) {
      throw new Error(`rules/ replaces "## ${heading}", but APPEND_SYSTEM.md has no such section`);
    }
  }

  const body = sections.map((section) => overrides.get(section.heading) ?? section.text).join('\n\n');
  const note = `<!-- ${GENERATED} from ~/.pi/agent/APPEND_SYSTEM.md and ~/.pi/pi-workflow/rules/. Edit those, then rerun it. -->`;
  return `${MARKDOWN_MARKERS.start}\n${note}\n\n${body}\n${MARKDOWN_MARKERS.end}\n`;
}

function splitSections(markdown) {
  const sections = [{ heading: null, lines: [] }];
  let inFence = false;

  for (const line of markdown.split('\n')) {
    if (line.startsWith('```')) inFence = !inFence;
    if (!inFence && line.startsWith('## ')) sections.push({ heading: line.slice(3).trim(), lines: [] });
    sections.at(-1).lines.push(line);
  }

  return sections
    .map(({ heading, lines }) => ({ heading, text: lines.join('\n').trim() }))
    .filter((section) => section.text !== '');
}

function loadRuleOverrides() {
  const overrides = new Map();

  for (const file of readdirSync(RULES_DIR).filter((name) => name.endsWith('.md'))) {
    const text = readFileSync(join(RULES_DIR, file), 'utf8').trim();
    const heading = /^## (.+)/.exec(text)?.[1].trim();
    if (!heading) throw new Error(`rules/${file} must start with a "## " heading`);
    overrides.set(heading, text);
  }

  return overrides;
}

// A new block goes first in Markdown, so the rules lead, and last in TOML, where a table placed
// earlier would capture the top-level keys that follow it.
function writeBlock(path, newBlock, markers, { byteLimit = Infinity, append = false } = {}) {
  const existing = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const block = findBlock(existing, markers);
  if (!block) throw new Error(`${path} needs one pi-workflow start marker before one end marker, or neither; fix it by hand`);

  let content;
  if (block.found) content = existing.slice(0, block.start) + newBlock + existing.slice(block.end).replace(/^\r?\n/, '');
  else if (existing === '') content = newBlock;
  else content = append ? `${existing.replace(/\n*$/, '\n')}\n${newBlock}` : `${newBlock}\n${existing}`;

  const bytes = Buffer.byteLength(content);
  if (bytes > byteLimit) throw new Error(`${path} would be ${bytes} bytes; Codex reads only the first ${byteLimit}`);

  writeIfChanged(path, content);
}

// Markers count only as whole lines, so the same text inside a paragraph or a TOML string is left alone.
// Returns undefined when the markers are ambiguous.
function findBlock(text, markers) {
  const starts = markerLines(text, markers.start);
  const ends = markerLines(text, markers.end);

  if (starts.length === 0 && ends.length === 0) return { found: false };
  if (starts.length !== 1 || ends.length !== 1 || ends[0] < starts[0]) return undefined;

  return { found: true, start: starts[0], end: ends[0] + markers.end.length };
}

function markerLines(text, marker) {
  const pattern = new RegExp(`^${marker.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\r?$`, 'gm');
  return [...text.matchAll(pattern)].map((match) => match.index);
}

function syncSkills() {
  const wanted = new Map();

  for (const root of SKILL_SOURCES) {
    if (!existsSync(root)) {
      warn(`skill source ${root} is missing`);
      continue;
    }

    for (const name of readdirSync(root)) {
      const dir = join(root, name);
      if (!existsSync(join(dir, 'SKILL.md'))) continue;
      if (wanted.has(name)) warn(`skill ${name} is in two sources; keeping ${wanted.get(name)}`);
      else wanted.set(name, dir);
    }
  }

  for (const target of SKILL_TARGETS) linkSkills(target, wanted);
}

function linkSkills(targetRoot, wanted) {
  if (!DRY_RUN) mkdirSync(targetRoot, { recursive: true });
  const present = existsSync(targetRoot) ? readdirSync(targetRoot) : [];
  const stale = new Set();

  for (const name of present) {
    const path = join(targetRoot, name);
    if (!isManagedLink(path) || readlinkSync(path) === wanted.get(name)) continue;

    remove(path);
    stale.add(name);
  }

  for (const [name, source] of wanted) {
    const path = join(targetRoot, name);

    // A dry run leaves stale links in place, so they still count as missing here.
    if (!pathExists(path) || stale.has(name)) {
      log(`link ${path} -> ${source}`);
      if (!DRY_RUN) symlinkSync(source, path);
    } else if (!isManagedLink(path) && !sameTarget(path, source)) {
      warn(`${path} exists and pi-workflow does not manage it; skipped skill ${name}`);
    }
  }
}

function syncAgents() {
  const written = new Set();

  for (const file of readdirSync(join(PI_AGENT, 'agents')).filter((name) => name.endsWith('.md'))) {
    const agent = parseAgent(join(PI_AGENT, 'agents', file));
    const preferred = preferredModel(agent);

    written.add(writeManaged(join(CLAUDE_AGENTS, `${agent.name}.md`), claudeAgentFile(agent, preferred)));
    written.add(writeManaged(join(CODEX_AGENTS, `${agent.name}.toml`), codexAgentFile(agent, preferred)));
  }

  // Filtering by extension keeps one pass from deleting the other's files when both folders are the same.
  for (const [dir, extension] of [[CLAUDE_AGENTS, '.md'], [CODEX_AGENTS, '.toml']]) {
    if (!existsSync(dir)) continue;

    for (const name of readdirSync(dir).filter((file) => file.endsWith(extension))) {
      const path = join(dir, name);
      if (!written.has(path) && isManagedFile(path)) remove(path);
    }
  }
}

function parseAgent(file) {
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(readFileSync(file, 'utf8'));
  if (!match) throw new Error(`${file} has no frontmatter`);

  const fields = {};

  for (const line of match[1].split('\n')) {
    if (line.trim() === '') continue;

    const field = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (!field) throw new Error(`${file}: unsupported frontmatter line "${line}"`);
    fields[field[1]] = parseYamlValue(field[2]);
  }

  if (typeof fields.description !== 'string') throw new Error(`${file} has no description`);

  return { name: basename(file, '.md'), file, fields, body: match[2].trim() };
}

function parseYamlValue(raw) {
  if (raw.startsWith("'") && raw.endsWith("'")) return raw.slice(1, -1).replaceAll("''", "'");
  if (raw.startsWith('"') && raw.endsWith('"')) return JSON.parse(raw);
  if (raw.startsWith('[') && raw.endsWith(']')) return splitList(raw.slice(1, -1));
  if (raw === 'true' || raw === 'false') return raw === 'true';
  return raw;
}

function splitList(text) {
  return text.split(',').map((item) => item.trim()).filter(Boolean);
}

function preferredModel(agent) {
  const { model, thinking } = agent.fields;
  if (!model) return undefined;

  const [prefix, ...rest] = model.split('/');
  const provider = PROVIDERS[prefix];
  if (!provider) throw new Error(`${agent.file}: no T3 provider for model ${model}`);

  return { provider, model: rest.join('/'), effort: EFFORTS.includes(thinking) ? thinking : undefined };
}

function modelFor(harness, preferred) {
  if (!preferred) return {};

  const model = preferred.provider === harness ? preferred.model : FALLBACK_MODELS[harness];
  // gpt-6-astra accepts only low, medium, or high (Model Routing).
  const effort = model === 'gpt-6-astra' && ['xhigh', 'max'].includes(preferred.effort) ? 'high' : preferred.effort;
  return { model, effort };
}

function describe(agent, preferred) {
  const description = agent.fields.description.trim();
  if (!preferred) return description;

  const effort = preferred.effort ? ` at ${preferred.effort}` : '';
  return `${description} Preferred model: ${preferred.provider} / ${preferred.model}${effort}.`;
}

function preloadedSkills(agent) {
  const { skills } = agent.fields;
  if (Array.isArray(skills)) return skills;
  return typeof skills === 'string' ? splitList(skills) : [];
}

function piTools(agent) {
  return splitList(String(agent.fields.tools ?? '')).filter((tool) => !tool.startsWith('ext:'));
}

function canEdit(agent) {
  const tools = piTools(agent);
  const disallowed = splitList(String(agent.fields.disallowed_tools ?? ''));
  return ['write', 'edit'].some((tool) => tools.includes(tool) && !disallowed.includes(tool));
}

function claudeAgentFile(agent, preferred) {
  const { model, effort } = modelFor('claudeAgent', preferred);
  const skills = preloadedSkills(agent);
  const lines = ['---', `# ${GENERATED} from ~/.pi/agent/agents/${agent.name}.md`, `name: ${agent.name}`];
  lines.push(`description: ${JSON.stringify(describe(agent, preferred))}`);

  // An allowlist would hide MCP servers from agents that pi gives every extension tool.
  if (agent.fields.tools && agent.fields.extensions !== true) lines.push(`tools: ${claudeTools(agent).join(', ')}`);
  if (!canEdit(agent)) lines.push('disallowedTools: Write, Edit, NotebookEdit');
  if (model) lines.push(`model: ${model}`);
  if (effort) lines.push(`effort: ${effort}`);
  if (agent.fields.max_turns) lines.push(`maxTurns: ${agent.fields.max_turns}`);
  if (skills.length > 0) lines.push('skills:', ...skills.map((skill) => `  - ${skill}`));

  const toolNote = 'Tool names here come from pi: read, grep, find, bash, edit, and write mean Read, Grep, Glob, Bash, Edit, and Write.';
  return `${lines.join('\n')}\n---\n\n${toolNote}\n\n${agent.body}\n`;
}

function claudeTools(agent) {
  const tools = piTools(agent).map((tool) => {
    if (!CLAUDE_TOOLS[tool]) throw new Error(`${agent.file}: no Claude Code tool for pi tool "${tool}"`);
    return CLAUDE_TOOLS[tool];
  });

  if (agent.fields.skills === true) tools.push('Skill');
  return [...new Set(tools)];
}

function codexAgentFile(agent, preferred) {
  const { model, effort } = modelFor('codex', preferred);
  const skills = preloadedSkills(agent);

  const preface = ['These instructions were written for pi. Where they say read, grep, find, or ls, use read-only shell commands; where they say edit or write, use apply_patch.'];
  if (!canEdit(agent)) preface.push('You are read-only: do not modify files, and run only commands that leave the system unchanged.');
  if (skills.length > 0) preface.push(`Before starting, load these skills: ${skills.join(', ')}.`);

  const lines = [`# ${GENERATED} from ~/.pi/agent/agents/${agent.name}.md`, `name = ${tomlString(agent.name)}`];
  lines.push(`description = ${tomlString(describe(agent, preferred))}`);
  if (model) lines.push(`model = ${tomlString(model)}`);
  if (effort) lines.push(`model_reasoning_effort = ${tomlString(effort)}`);
  lines.push(`developer_instructions = ${tomlMultiline(`${preface.join('\n')}\n\n${agent.body}`)}`);

  return `${lines.join('\n')}\n`;
}

// JSON escapes every control character TOML forbids except DEL.
export function tomlString(text) {
  return JSON.stringify(text).replaceAll('\x7f', '\\u007f');
}

export function tomlMultiline(text) {
  const escaped = text
    .replaceAll('\r\n', '\n')
    .replaceAll('\\', '\\\\')
    .replaceAll('"""', '""\\"')
    .replace(/[\x00-\x08\x0b-\x1f\x7f]/g, (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`);

  return `"""\n${escaped}\n"""`;
}

function syncClaudeServers() {
  const current = readJson(CLAUDE_JSON)?.mcpServers ?? {};
  const changes = [];

  for (const [name, server] of Object.entries(MCP_SERVERS)) {
    const wanted = server.url ? { type: 'http', url: server.url } : { type: 'stdio', command: server.command, args: server.args, env: OWNER_ENV };
    const existing = current[name];
    if (sameJson(existing, wanted)) continue;

    if (existing && !isOwnedClaudeServer(existing)) {
      warn(`Claude MCP server ${name} exists and pi-workflow does not manage it; skipped`);
      continue;
    }

    if (existing) changes.push(['mcp', 'remove', '-s', 'user', name]);
    changes.push(['mcp', 'add-json', '-s', 'user', name, JSON.stringify(wanted)]);
  }

  for (const [name, existing] of Object.entries(current)) {
    if (!MCP_SERVERS[name] && isOwnedClaudeServer(existing)) changes.push(['mcp', 'remove', '-s', 'user', name]);
  }

  for (const args of changes) {
    log(`claude ${args.slice(0, 5).join(' ')}`);
    if (!DRY_RUN && runCli('claude', args, CLAUDE_ENV) !== 'ok') return;
  }
}

function isOwnedClaudeServer(server) {
  return server?.env?.PI_WORKFLOW === OWNER_ENV.PI_WORKFLOW;
}

function syncCodexServers() {
  const existing = existsSync(CODEX_CONFIG) ? readFileSync(CODEX_CONFIG, 'utf8') : '';
  const userServers = userCodexServers(existing);

  // A same-named server the user defined wins: two tables with one name would make config.toml invalid.
  const tables = Object.entries(MCP_SERVERS)
    .filter(([name]) => !userServers.has(name))
    .map(([name, server]) => codexServerTable(name, server));
  const block = `${TOML_MARKERS.start}\n# ${GENERATED}. Edit MCP_SERVERS there, then rerun it.\n\n${tables.join('\n')}${TOML_MARKERS.end}\n`;

  writeBlock(CODEX_CONFIG, block, TOML_MARKERS, { append: true });
  if (DRY_RUN) return;

  const written = readFileSync(CODEX_CONFIG, 'utf8');
  if (written === existing || runCli('codex', ['mcp', 'list', '--json'], CODEX_ENV) !== 'failed') return;

  // Codex reads this file on every start, so a file it rejects goes back, unless someone changed it since.
  if (readFileSync(CODEX_CONFIG, 'utf8') !== written) {
    throw new Error(`Codex rejected ${CODEX_CONFIG}, and it changed again before sync could restore it; fix it by hand`);
  }

  writeIfChanged(CODEX_CONFIG, existing);
  throw new Error(`${CODEX_CONFIG} was restored because Codex rejected the new MCP servers`);
}

// Codex's own parser sees every TOML form a user might write. Without a parseable config, fall back
// to the table headers outside the block.
function userCodexServers(text) {
  const block = findBlock(text, TOML_MARKERS);
  const inside = block?.found ? text.slice(block.start, block.end) : '';
  const outside = block?.found ? text.slice(0, block.start) + text.slice(block.end) : text;

  const listed = codexServerNames();
  if (listed) {
    const ours = tableNames(inside);
    return new Set(listed.filter((name) => !ours.has(name)));
  }

  return tableNames(outside);
}

function codexServerNames() {
  const run = spawnSync('codex', ['mcp', 'list', '--json'], cliOptions(CODEX_ENV));
  if (run.status !== 0) return undefined;

  try {
    return JSON.parse(run.stdout).map((server) => server.name);
  } catch {
    return undefined;
  }
}

function tableNames(toml) {
  return new Set([...toml.matchAll(/^\s*\[\s*mcp_servers\s*\.\s*["']?([\w-]+)["']?\s*\]/gm)].map((match) => match[1]));
}

function codexServerTable(name, server) {
  const lines = [`[mcp_servers.${name}]`];

  if (server.url) lines.push(`url = ${tomlString(server.url)}`);
  else lines.push(`command = ${tomlString(server.command)}`, `args = [${server.args.map(tomlString).join(', ')}]`);

  for (const [key, value] of Object.entries(server.codex ?? {})) {
    lines.push(`${key} = ${Array.isArray(value) ? `[${value.map(tomlString).join(', ')}]` : value}`);
  }

  return `${lines.join('\n')}\n`;
}

// Run from / so Codex never mixes in the config of a trusted project sync happens to start in.
function cliOptions(env) {
  return { env, cwd: '/', encoding: 'utf8', timeout: CLI_TIMEOUT_MS };
}

function runCli(command, args, env) {
  const run = spawnSync(command, args, cliOptions(env));

  if (run.error?.code === 'ENOENT') {
    warn(`${command} is not on PATH; skipped its MCP servers`);
    return 'missing';
  }

  if (run.status !== 0) {
    warn(`${command} ${args.slice(0, 5).join(' ')} failed: ${(run.stderr || run.stdout || String(run.error)).trim()}`);
    return 'failed';
  }

  return 'ok';
}

function readJson(path) {
  if (!existsSync(path)) return undefined;

  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    throw new Error(`${path} is not valid JSON: ${error.message}`);
  }
}

function sameJson(a, b) {
  return canonicalJson(a) === canonicalJson(b);
}

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`;
  }

  return JSON.stringify(value);
}

function writeManaged(path, content) {
  // lstat-based: a symlink here, even a dangling one, belongs to someone else and is never written through.
  if (pathExists(path) && !isManagedFile(path)) {
    warn(`${path} exists and pi-workflow does not manage it; skipped`);
  } else {
    writeIfChanged(path, content);
  }

  return path;
}

function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return;

  log(`write ${path}`);
  if (DRY_RUN) return;

  if (pathExists(path) && !existsSync(path)) throw new Error(`${path} is a broken symlink; fix it by hand`);

  // Write beside the real file and rename it into place, so a reader never sees half a file.
  // Resolving the path first keeps a dotfile symlink pointing at the updated file.
  const target = existsSync(path) ? realpathSync(path) : path;
  const temp = `${target}.${process.pid}.tmp`;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(temp, content, { mode: existsSync(target) ? statSync(target).mode : 0o644 });
  renameSync(temp, target);
}

function remove(path) {
  log(`remove ${path}`);
  // rmSync leaves dangling symlinks in place and throws EISDIR on links to directories; unlinkSync removes just the link.
  if (!DRY_RUN) unlinkSync(path);
}

// Only the file named after its own source counts, so an edited copy of a generated agent is the user's.
function isManagedFile(path) {
  const source = `${basename(path).replace(/\.(md|toml)$/, '')}.md`;
  return lstatSync(path).isFile() && readFileSync(path, 'utf8').includes(`# ${GENERATED} from ~/.pi/agent/agents/${source}\n`);
}

function isManagedLink(path) {
  return pathExists(path) && lstatSync(path).isSymbolicLink() && SKILL_SOURCES.includes(dirname(readlinkSync(path)));
}

function sameTarget(path, source) {
  try {
    return realpathSync(path) === realpathSync(source);
  } catch {
    return false;
  }
}

function pathExists(path) {
  try {
    lstatSync(path);
    return true;
  } catch {
    return false;
  }
}

function log(message) {
  console.log(DRY_RUN ? `[dry-run] ${message}` : message);
}

function warn(message) {
  console.warn(`warning: ${message}`);
}
